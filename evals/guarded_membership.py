"""Validate frozen, reviewed membership implementations with evaluator-side inputs."""
import argparse
from hashlib import sha256
import json
import math
from pathlib import Path
import random
import secrets
import statistics
import time
import tracemalloc


EVALS = Path(__file__).resolve().parent
BASELINE = EVALS / "fixtures" / "algorithm" / "membership.py"
MEMORY_CAP = 64 * 1024
WIDE_MAX_RATIO = 0.75
SMALL_MAX_RATIO = 1.25
SMALL_ABSOLUTE_TOLERANCE_NS = 150
REPEATS = 21


def workload(seed):
    rng = random.Random(seed)
    wide = []
    for size in (34_000, 41_000):
        values = rng.sample(range(-20 * size, 20 * size), size)
        queries = rng.choices(values, k=100) + rng.choices(range(10**25, 10**25 + 200), k=100)
        rng.shuffle(queries)
        wide.append((values, queries))
    small = [
        ([], []), ([], [0, -1]), ([1, 1, -1], [1, 0, -1, 1]),
        ([-10**30, 10**30, 0], [-10**30, 10**30 + 1, 0]),
    ]
    for size in (4, 6, 10, 15):
        values = rng.choices(range(-20, 21), k=size)
        small.append((values, rng.choices(range(-20, 21), k=5)))
    return wide, small


def load_frozen(path):
    # Reviewed candidates only. Execution here does not sandbox Python code.
    content = path.read_bytes()
    namespace = {}
    exec(compile(content, str(path), "exec"), namespace)
    return sha256(content).hexdigest(), namespace["batch_membership"]


def exact_match(candidate, cases):
    for values, queries in cases:
        values_copy, queries_copy = values.copy(), queries.copy()
        expected = [query in values for query in queries]
        output = candidate(values_copy, queries_copy)
        if (type(output) is not list or any(type(item) is not bool for item in output)
                or output != expected or values_copy != values or queries_copy != queries):
            return False
    return True


def timed_batch(fn, cases, loops):
    start = time.perf_counter_ns()
    for _ in range(loops):
        for values, queries in cases:
            fn(values, queries)
    return (time.perf_counter_ns() - start) / (loops * len(cases))


def paired_samples(baseline, candidate, cases, loops):
    functions = (baseline, candidate)
    samples = ([], [])
    for fn in functions:
        timed_batch(fn, cases, loops)
    for repeat in range(REPEATS):
        order = (0, 1) if repeat % 2 == 0 else (1, 0)
        for index in order:
            samples[index].append(timed_batch(functions[index], cases, loops))
    return samples


def peak_traced_bytes(fn, cases):
    peaks = []
    for values, queries in cases:
        tracemalloc.start()
        try:
            output = fn(values, queries)
            peaks.append(tracemalloc.get_traced_memory()[1])
        finally:
            tracemalloc.stop()
        del output
    return max(peaks)


def p95(samples):
    return sorted(samples)[math.ceil(0.95 * len(samples)) - 1]


def evaluate(baseline, candidate, wide, small):
    if not exact_match(candidate, wide + small):
        return {"guards": {"exact_output_and_inputs": False}, "retain": False}
    wide_baseline, wide_candidate = paired_samples(baseline, candidate, wide, loops=1)
    small_baseline, small_candidate = paired_samples(baseline, candidate, small, loops=750)
    peak = peak_traced_bytes(candidate, wide)
    wide_ratio = statistics.median(wide_candidate) / statistics.median(wide_baseline)
    small_limit_ns = max(p95(small_baseline) * SMALL_MAX_RATIO, p95(small_baseline) + SMALL_ABSOLUTE_TOLERANCE_NS)
    guards = {
        "exact_output_and_inputs": True,
        "wide_median_improvement": wide_ratio <= WIDE_MAX_RATIO,
        "small_p95_batch_guard": p95(small_candidate) <= small_limit_ns,
        "peak_traced_memory": peak <= MEMORY_CAP,
    }
    return {
        "guards": guards,
        "retain": all(guards.values()),
        "wide_ratio": wide_ratio,
        "peak_traced_bytes": peak,
        "baseline_peak_traced_bytes": peak_traced_bytes(baseline, wide),
        "wide_baseline_ns": wide_baseline,
        "wide_candidate_ns": wide_candidate,
        "small_baseline_ns": small_baseline,
        "small_candidate_ns": small_candidate,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("candidates", nargs="+", type=Path, help="Frozen and reviewed Python files")
    parser.add_argument("--seed", type=int, help="Evaluator-only input seed, generated by default")
    args = parser.parse_args()
    baseline_digest, baseline = load_frozen(BASELINE)
    seed = secrets.randbits(64) if args.seed is None else args.seed
    wide, small = workload(seed)
    results = []
    for path in args.candidates:
        digest, candidate = load_frozen(path)
        results.append({"candidate": path.name, "sha256": digest, **evaluate(baseline, candidate, wide, small)})
    print(json.dumps({"seed": seed, "baseline_sha256": baseline_digest, "results": results}, indent=2))


if __name__ == "__main__":
    main()
